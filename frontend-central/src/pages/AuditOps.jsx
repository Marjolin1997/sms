import { t } from "../i18n.jsx";
import { Card, DetailList, DetailRow, Empty, StatusBadge } from "../ui.jsx";
import { OpsPage, Stamp } from "../ops/components.jsx";
import { buildHash } from "../routes.js";

// Central guarda VETËM gjendjen e fundit të raportit Enterprise (M11-D2): këtu nuk shfaqet histori, trend apo grafik.
export default function AuditOps() {
  return (
    <OpsPage>
      {(o) => {
        const s = o.metrics.snapshot;
        return (
          <>
            <Card title={t("Operations: current state only")} subtitle={t("Central keeps only the latest report from each Enterprise deployment. There is no history or trend to show.")}>
              {!s.present ? <Empty title={t("No Enterprise report received")}>{t("No Enterprise deployment has reported yet, so nothing is shown here.")}</Empty> : (
                <DetailList>
                  <DetailRow label={t("Freshness")}>{s.state ? <StatusBadge>{s.state}</StatusBadge> : "-"}</DetailRow>
                  <DetailRow label={t("Generated by Enterprise")}><Stamp value={s.generatedAt} /></DetailRow>
                  <DetailRow label={t("Received by Central")}><Stamp value={s.receivedAt} /></DetailRow>
                  <DetailRow label={t("Age")}>{s.ageSeconds != null ? t("{n} s", { n: s.ageSeconds }) : "-"}</DetailRow>
                  <DetailRow label={t("Source revision")}><span className="mono">{s.sourceRevision || "-"}</span></DetailRow>
                  <DetailRow label={t("Reporters")}>{s.deployments}</DetailRow>
                </DetailList>
              )}
              <p><a href={buildHash("ops")}>{t("Open Sender Readiness")}</a> · <a href={buildHash("ops-alerts")}>{t("Open Alerts")}</a></p>
            </Card>
          </>
        );
      }}
    </OpsPage>
  );
}
